'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
exports.runRepeated = async (browser, errors, baseUrl) => {
  const page = await browser.newPage();
  page.on('pageerror', e => errors.push(e.message));
  const contract={id:'CTR-REPEATED-DEMO',supplier_id:'FOR-031',approver_id:'EMP-014',title:'  SERVIÇOS   de manutenção '};
  const imported=await page.request.post(`${baseUrl}/api/import`,{data:{actor:'Analista tipologia sintética',synthetic:true,dataset:{employees:[],suppliers:[],contracts:[contract]}}});
  assert.ok(imported.ok());
  await page.goto(`${baseUrl}/#inteligencia`);
  await page.getByTestId('detect-repeated').click();
  await page.waitForFunction(() => !document.querySelector('[data-testid="detect-repeated"]') || document.querySelector('[data-testid="detect-repeated"]').disabled);
  const state=await (await page.request.get(`${baseUrl}/api/state`)).json();
  const cases=state.cases.filter(c=>c.rule.id==='repeated-contract-profile');
  assert.ok(cases.some(c=>c.records.contract.id==='CTR-1042'));
  assert.ok(cases.some(c=>c.records.contract.id===contract.id));
  const repeated=cases.find(c=>c.records.contract.id===contract.id);
  await page.goto(`${baseUrl}/?case_id=${repeated.id}#inteligencia`);
  await page.getByTestId('generate-dossier').click();
  await page.getByTestId('dossier').waitFor();
  await page.getByTestId('dossier').getByText(/não se conclui duplicidade financeira/).waitFor();
  const saved=await (await page.request.get(`${baseUrl}/api/state?case_id=${repeated.id}`)).json();
  assert.equal(saved.case.dossier.mode,'local');
  assert.equal(saved.case.decision,null);
  assert.equal(saved.case.rule.experimental,true);
  await page.screenshot({path:path.resolve('output/validation/desktop-repeated.png'),fullPage:true});
  await page.close();
  const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  mobile.on('pageerror',e=>errors.push(e.message));
  await mobile.goto(`${baseUrl}/?case_id=${repeated.id}#inteligencia`);
  await mobile.getByTestId('dossier').waitFor();
  await mobile.getByTestId('dossier').scrollIntoViewIfNeeded();
  assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await mobile.screenshot({path:path.resolve('output/validation/mobile-repeated.png')});
  fs.writeFileSync('output/validation/repeated.json',JSON.stringify({rule:repeated.rule.id,experimental:true,caseIds:cases.map(c=>c.id),desktop:true,mobile:true,localDossier:true},null,2));
  await mobile.close();
};
